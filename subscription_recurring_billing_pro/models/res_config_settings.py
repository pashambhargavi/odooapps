# -*- coding: utf-8 -*-
from odoo import models, fields


class ResConfigSettings(models.TransientModel):
    _inherit = 'res.config.settings'

    subscription_auto_post_invoices = fields.Boolean(
        string='Auto-Post Recurring Invoices',
        config_parameter='subscription_recurring_billing_pro.subscription_auto_post_invoices',
        default=False,
        help='Automatically validate customer invoices generated by recurring contracts.'
    )
    subscription_default_grace_days = fields.Integer(
        string='Default Dunning Grace Days',
        config_parameter='subscription_recurring_billing_pro.subscription_default_grace_days',
        default=7,
        help='Grace period before marking an overdue subscription as paused.'
    )
