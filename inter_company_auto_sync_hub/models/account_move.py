# -*- coding: utf-8 -*-
import logging
from odoo import models, fields, api, _
from odoo.exceptions import UserError

_logger = logging.getLogger(__name__)



class AccountMove(models.Model):
    _inherit = 'account.move'

    intercompany_move_id = fields.Many2one(
        'account.move',
        string='Mirrored Inter-Company Entry',
        copy=False,
        readonly=True,
        help='Reciprocal Customer Invoice or Vendor Bill automatically created in the sister entity.'
    )
    auto_intercompany_created = fields.Boolean(
        string='Inter-Company Generated',
        copy=False,
        default=False,
        help='Technical flag to identify accounting entries generated by inter-company automation.'
    )
    is_intercompany = fields.Boolean(
        string='Is Inter-Company Move',
        compute='_compute_is_intercompany',
        store=True
    )

    @api.depends('partner_id', 'company_id')
    def _compute_is_intercompany(self):
        rule_obj = self.env['inter.company.rule']
        for move in self:
            if move.partner_id and move.company_id:
                rule = rule_obj.search([
                    ('company_id', '=', move.company_id.id),
                    ('partner_id', '=', move.partner_id.id),
                    ('active', '=', True)
                ], limit=1)
                move.is_intercompany = bool(rule)
            else:
                move.is_intercompany = False

    def action_post(self):
        res = super(AccountMove, self).action_post()
        rule_obj = self.env['inter.company.rule'].sudo()
        log_obj = self.env['inter.company.log'].sudo()

        for move in self:
            if move.auto_intercompany_created or move.intercompany_move_id:
                continue

            if move.move_type not in ('out_invoice', 'in_invoice'):
                continue

            rule = rule_obj.search([
                ('company_id', '=', move.company_id.id),
                ('partner_id', '=', move.partner_id.id),
                ('active', '=', True),
                ('sync_invoice_to_bill', '=', True)
            ], limit=1)

            if not rule:
                continue

            target_company = rule.target_company_id
            target_partner = rule.target_partner_id
            if not target_partner:
                target_partner = move.company_id.partner_id

            reciprocal_type = 'in_invoice' if move.move_type == 'out_invoice' else 'out_invoice'
            target_journal = self.env['account.journal'].with_company(target_company).sudo().search([
                ('type', '=', 'purchase' if reciprocal_type == 'in_invoice' else 'sale'),
                ('company_id', '=', target_company.id)
            ], limit=1)

            inv_date = move.invoice_date or fields.Date.today()
            due_date = move.invoice_date_due or inv_date

            bill_vals = {
                'move_type': reciprocal_type,
                'company_id': target_company.id,
                'partner_id': target_partner.id,
                'invoice_date': inv_date,
                'invoice_date_due': due_date,
                'ref': move.name,
                'auto_intercompany_created': True,
                'intercompany_move_id': move.id,
                'invoice_line_ids': []
            }
            if target_journal:
                bill_vals['journal_id'] = target_journal.id

            target_account = self.env['account.account'].with_company(target_company).sudo().search([
                ('account_type', 'in', ('expense', 'expense_direct_cost', 'cost_of_revenue'))
            ], limit=1)

            for line in move.invoice_line_ids:
                if line.display_type in ('line_section', 'line_note'):
                    continue

                line_account = target_account.id if target_account else (line.account_id.id if line.account_id else False)
                line_vals = {
                    'product_id': line.product_id.id if line.product_id else False,
                    'quantity': line.quantity,
                    'price_unit': line.price_unit,
                    'name': line.name or (line.product_id.display_name if line.product_id else 'Inter-Company Item'),
                }
                if line_account:
                    line_vals['account_id'] = line_account

                bill_vals['invoice_line_ids'].append((0, 0, line_vals))

            try:
                reciprocal_move = self.env['account.move'].with_company(target_company).sudo().create(bill_vals)
                move.intercompany_move_id = reciprocal_move.id

                if rule.auto_validate_bill:
                    reciprocal_move.with_company(target_company).sudo().action_post()

                target_ref = reciprocal_move.name or reciprocal_move.ref or (_('Draft Bill #%s') % reciprocal_move.id)

                log_obj.create({
                    'rule_id': rule.id,
                    'name': _('Invoice %s -> Bill %s') % (move.name, target_ref),
                    'source_company_id': move.company_id.id,
                    'target_company_id': target_company.id,
                    'source_doc_type': 'invoice',
                    'source_doc_ref': move.name or 'Draft',
                    'target_doc_type': 'invoice',
                    'target_doc_ref': target_ref,
                    'amount': reciprocal_move.amount_total,
                    'currency_id': reciprocal_move.currency_id.id,
                    'state': 'success',
                    'details': _('Successfully mirrored %s %s to %s %s in company %s.') % (
                        move.move_type, move.name, reciprocal_type, target_ref, target_company.name
                    )
                })

            except Exception as e:
                _logger.exception("Inter-company invoice mirroring failed: %s", e)
                log_obj.create({
                    'rule_id': rule.id,
                    'name': _('Failed Invoice %s Mirroring') % move.name,
                    'source_company_id': move.company_id.id,
                    'target_company_id': target_company.id,
                    'source_doc_type': 'invoice',
                    'source_doc_ref': move.name,
                    'target_doc_type': 'invoice',
                    'target_doc_ref': 'N/A',
                    'amount': move.amount_total,
                    'currency_id': move.currency_id.id,
                    'state': 'error',
                    'details': str(e)
                })

        return res

    def action_view_intercompany_move(self):
        self.ensure_one()
        if not self.intercompany_move_id:
            raise UserError(_('No mirrored accounting entry found for this transaction.'))

        return {
            'name': _('Mirrored Inter-Company Entry'),
            'type': 'ir.actions.act_window',
            'res_model': 'account.move',
            'res_id': self.intercompany_move_id.id,
            'view_mode': 'form',
            'target': 'current',
        }
