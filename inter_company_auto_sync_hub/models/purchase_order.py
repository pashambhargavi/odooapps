# -*- coding: utf-8 -*-
from odoo import models, fields, api, _
from odoo.exceptions import UserError


class PurchaseOrder(models.Model):
    _inherit = 'purchase.order'

    intercompany_sale_order_id = fields.Many2one(
        'sale.order',
        string='Mirrored Sales Order',
        copy=False,
        readonly=True,
        help='Reciprocal Sales Order automatically generated in the sister entity.'
    )
    auto_intercompany_created = fields.Boolean(
        string='Inter-Company Generated',
        copy=False,
        default=False,
        help='Technical flag to identify documents generated by inter-company automation.'
    )
    is_intercompany = fields.Boolean(
        string='Is Inter-Company Order',
        compute='_compute_is_intercompany',
        store=True
    )

    @api.depends('partner_id', 'company_id')
    def _compute_is_intercompany(self):
        rule_obj = self.env['inter.company.rule']
        for po in self:
            if po.partner_id and po.company_id:
                rule = rule_obj.search([
                    ('company_id', '=', po.company_id.id),
                    ('partner_id', '=', po.partner_id.id),
                    ('active', '=', True)
                ], limit=1)
                po.is_intercompany = bool(rule)
            else:
                po.is_intercompany = False

    def button_confirm(self):
        res = super(PurchaseOrder, self).button_confirm()
        rule_obj = self.env['inter.company.rule'].sudo()
        log_obj = self.env['inter.company.log'].sudo()

        for po in self:
            if po.auto_intercompany_created or po.intercompany_sale_order_id:
                continue

            rule = rule_obj.search([
                ('company_id', '=', po.company_id.id),
                ('partner_id', '=', po.partner_id.id),
                ('active', '=', True),
                ('sync_po_to_so', '=', True)
            ], limit=1)

            if not rule:
                continue

            target_company = rule.target_company_id
            target_partner = rule.target_partner_id
            if not target_partner:
                # Find or use partner tied to source company
                target_partner = po.company_id.partner_id

            so_vals = {
                'company_id': target_company.id,
                'partner_id': target_partner.id,
                'client_order_ref': po.name,
                'origin': _('Inter-Company PO %s') % po.name,
                'auto_intercompany_created': True,
                'intercompany_purchase_order_id': po.id,
                'order_line': []
            }

            for line in po.order_line:
                if line.display_type in ('line_section', 'line_note'):
                    continue

                transfer_price = rule.calculate_transfer_price(line.product_id, line.price_unit)
                uom_id = line.product_uom_id.id if hasattr(line, 'product_uom_id') and line.product_uom_id else (line.product_uom.id if hasattr(line, 'product_uom') and line.product_uom else line.product_id.uom_id.id)

                so_vals['order_line'].append((0, 0, {
                    'product_id': line.product_id.id,
                    'product_uom_qty': line.product_qty,
                    'product_uom_id': uom_id,
                    'price_unit': transfer_price,
                    'name': line.name or line.product_id.display_name,
                }))

            try:
                sale_order = self.env['sale.order'].with_company(target_company).sudo().create(so_vals)
                po.intercompany_sale_order_id = sale_order.id

                if rule.auto_confirm_so:
                    sale_order.with_company(target_company).sudo().action_confirm()

                log_obj.create({
                    'rule_id': rule.id,
                    'name': _('PO %s -> SO %s') % (po.name, sale_order.name),
                    'source_company_id': po.company_id.id,
                    'target_company_id': target_company.id,
                    'source_doc_type': 'purchase_order',
                    'source_doc_ref': po.name,
                    'target_doc_type': 'sale_order',
                    'target_doc_ref': sale_order.name,
                    'amount': sale_order.amount_total,
                    'currency_id': sale_order.currency_id.id,
                    'state': 'success',
                    'details': _('Successfully mirrored PO %s to SO %s in company %s.') % (
                        po.name, sale_order.name, target_company.name
                    )
                })

            except Exception as e:
                log_obj.create({
                    'rule_id': rule.id,
                    'name': _('Failed PO %s Mirroring') % po.name,
                    'source_company_id': po.company_id.id,
                    'target_company_id': target_company.id,
                    'source_doc_type': 'purchase_order',
                    'source_doc_ref': po.name,
                    'target_doc_type': 'sale_order',
                    'target_doc_ref': 'N/A',
                    'amount': po.amount_total,
                    'currency_id': po.currency_id.id,
                    'state': 'error',
                    'details': str(e)
                })

        return res

    def action_view_intercompany_so(self):
        self.ensure_one()
        if not self.intercompany_sale_order_id:
            raise UserError(_('No mirrored Sales Order found for this purchase order.'))

        return {
            'name': _('Mirrored Sales Order'),
            'type': 'ir.actions.act_window',
            'res_model': 'sale.order',
            'res_id': self.intercompany_sale_order_id.id,
            'view_mode': 'form',
            'target': 'current',
        }
