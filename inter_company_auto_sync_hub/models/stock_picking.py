# -*- coding: utf-8 -*-
from odoo import models, fields, api, _
from odoo.exceptions import UserError


class StockPicking(models.Model):
    _inherit = 'stock.picking'

    intercompany_picking_id = fields.Many2one(
        'stock.picking',
        string='Mirrored Stock Transfer',
        copy=False,
        readonly=True,
        help='Reciprocal Stock Receipt or Delivery automatically generated in the sister entity.'
    )
    auto_intercompany_created = fields.Boolean(
        string='Inter-Company Generated',
        copy=False,
        default=False,
        help='Technical flag to identify stock transfers generated by inter-company automation.'
    )
    is_intercompany = fields.Boolean(
        string='Is Inter-Company Transfer',
        compute='_compute_is_intercompany',
        store=True
    )

    @api.depends('partner_id', 'company_id')
    def _compute_is_intercompany(self):
        rule_obj = self.env['inter.company.rule']
        for pick in self:
            if pick.partner_id and pick.company_id:
                rule = rule_obj.search([
                    ('company_id', '=', pick.company_id.id),
                    ('partner_id', '=', pick.partner_id.id),
                    ('active', '=', True)
                ], limit=1)
                pick.is_intercompany = bool(rule)
            else:
                pick.is_intercompany = False

    def _action_done(self):
        res = super(StockPicking, self)._action_done()
        rule_obj = self.env['inter.company.rule'].sudo()
        log_obj = self.env['inter.company.log'].sudo()

        for pick in self:
            if pick.auto_intercompany_created or pick.intercompany_picking_id:
                continue

            if pick.picking_type_code != 'outgoing':
                continue

            rule = rule_obj.search([
                ('company_id', '=', pick.company_id.id),
                ('partner_id', '=', pick.partner_id.id),
                ('active', '=', True),
                ('sync_delivery_to_receipt', '=', True)
            ], limit=1)

            if not rule:
                continue

            target_company = rule.target_company_id
            target_partner = rule.target_partner_id or pick.company_id.partner_id

            # Find incoming picking type in target company
            incoming_type = self.env['stock.picking.type'].with_company(target_company).sudo().search([
                ('code', '=', 'incoming'),
                ('company_id', '=', target_company.id)
            ], limit=1)

            if not incoming_type:
                continue

            cust_location = self.env['stock.location'].with_company(target_company).sudo().search([
                ('usage', '=', 'supplier')
            ], limit=1)
            dest_location = incoming_type.default_location_dest_id or self.env['stock.location'].with_company(target_company).sudo().search([
                ('usage', '=', 'internal'),
                ('company_id', '=', target_company.id)
            ], limit=1)

            picking_vals = {
                'picking_type_id': incoming_type.id,
                'company_id': target_company.id,
                'partner_id': target_partner.id,
                'origin': _('Inter-Company Delivery %s') % pick.name,
                'location_id': cust_location.id if cust_location else 1,
                'location_dest_id': dest_location.id if dest_location else 1,
                'auto_intercompany_created': True,
                'intercompany_picking_id': pick.id,
            }

            try:
                target_picking = self.env['stock.picking'].with_company(target_company).sudo().create(picking_vals)
                pick.intercompany_picking_id = target_picking.id

                # Create moves
                for move in pick.move_ids:
                    qty = move.quantity or move.product_uom_qty
                    if qty <= 0:
                        continue

                    self.env['stock.move'].with_company(target_company).sudo().create({
                        'product_id': move.product_id.id,
                        'product_uom_qty': qty,
                        'product_uom': move.product_uom.id,
                        'location_id': target_picking.location_id.id,
                        'location_dest_id': target_picking.location_dest_id.id,
                        'picking_id': target_picking.id,
                        'company_id': target_company.id,
                    })

                target_picking.action_confirm()

                if rule.auto_validate_receipt:
                    # Set quantities and validate
                    for m in target_picking.move_ids:
                        m.quantity = m.product_uom_qty
                    target_picking.button_validate()

                log_obj.create({
                    'rule_id': rule.id,
                    'name': _('Delivery %s -> Receipt %s') % (pick.name, target_picking.name),
                    'source_company_id': pick.company_id.id,
                    'target_company_id': target_company.id,
                    'source_doc_type': 'picking',
                    'source_doc_ref': pick.name,
                    'target_doc_type': 'picking',
                    'target_doc_ref': target_picking.name,
                    'amount': 0.0,
                    'currency_id': pick.company_id.currency_id.id,
                    'state': 'success',
                    'details': _('Successfully mirrored Delivery %s to Receipt %s in company %s.') % (
                        pick.name, target_picking.name, target_company.name
                    )
                })

            except Exception as e:
                log_obj.create({
                    'rule_id': rule.id,
                    'name': _('Failed Delivery %s Mirroring') % pick.name,
                    'source_company_id': pick.company_id.id,
                    'target_company_id': target_company.id,
                    'source_doc_type': 'picking',
                    'source_doc_ref': pick.name,
                    'target_doc_type': 'picking',
                    'target_doc_ref': 'N/A',
                    'amount': 0.0,
                    'currency_id': pick.company_id.currency_id.id,
                    'state': 'error',
                    'details': str(e)
                })

        return res

    def action_view_intercompany_picking(self):
        self.ensure_one()
        if not self.intercompany_picking_id:
            raise UserError(_('No mirrored stock transfer found for this shipment.'))

        return {
            'name': _('Mirrored Stock Transfer'),
            'type': 'ir.actions.act_window',
            'res_model': 'stock.picking',
            'res_id': self.intercompany_picking_id.id,
            'view_mode': 'form',
            'target': 'current',
        }
