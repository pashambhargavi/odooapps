# -*- coding: utf-8 -*-
from odoo import models, fields, api, _
from odoo.exceptions import UserError


class SaleOrder(models.Model):
    _inherit = 'sale.order'

    intercompany_purchase_order_id = fields.Many2one(
        'purchase.order',
        string='Mirrored Purchase Order',
        copy=False,
        readonly=True,
        help='Reciprocal Purchase Order automatically generated in the sister entity.'
    )
    auto_intercompany_created = fields.Boolean(
        string='Inter-Company Generated',
        copy=False,
        default=False,
        help='Technical flag to identify documents generated by inter-company automation.'
    )
    is_intercompany = fields.Boolean(
        string='Is Inter-Company Order',
        compute='_compute_is_intercompany',
        store=True
    )

    @api.depends('partner_id', 'company_id')
    def _compute_is_intercompany(self):
        rule_obj = self.env['inter.company.rule']
        for so in self:
            if so.partner_id and so.company_id:
                rule = rule_obj.search([
                    ('company_id', '=', so.company_id.id),
                    ('partner_id', '=', so.partner_id.id),
                    ('active', '=', True)
                ], limit=1)
                so.is_intercompany = bool(rule)
            else:
                so.is_intercompany = False

    def action_confirm(self):
        res = super(SaleOrder, self).action_confirm()
        rule_obj = self.env['inter.company.rule'].sudo()
        log_obj = self.env['inter.company.log'].sudo()

        for so in self:
            if so.auto_intercompany_created or so.intercompany_purchase_order_id:
                continue

            rule = rule_obj.search([
                ('company_id', '=', so.company_id.id),
                ('partner_id', '=', so.partner_id.id),
                ('active', '=', True),
                ('sync_so_to_po', '=', True)
            ], limit=1)

            if not rule:
                continue

            target_company = rule.target_company_id
            target_partner = rule.target_partner_id
            if not target_partner:
                target_partner = so.company_id.partner_id

            po_vals = {
                'company_id': target_company.id,
                'partner_id': target_partner.id,
                'origin': _('Inter-Company SO %s') % so.name,
                'auto_intercompany_created': True,
                'intercompany_sale_order_id': so.id,
                'order_line': []
            }

            for line in so.order_line:
                if line.display_type in ('line_section', 'line_note'):
                    continue

                transfer_price = rule.calculate_transfer_price(line.product_id, line.price_unit)
                uom_id = line.product_uom_id.id if hasattr(line, 'product_uom_id') and line.product_uom_id else (line.product_uom.id if hasattr(line, 'product_uom') and line.product_uom else line.product_id.uom_id.id)

                po_vals['order_line'].append((0, 0, {
                    'product_id': line.product_id.id,
                    'product_qty': line.product_uom_qty,
                    'product_uom_id': uom_id,
                    'price_unit': transfer_price,
                    'name': line.name or line.product_id.display_name,
                    'date_planned': fields.Datetime.now(),
                }))

            try:
                purchase_order = self.env['purchase.order'].with_company(target_company).sudo().create(po_vals)
                so.intercompany_purchase_order_id = purchase_order.id

                if rule.auto_confirm_po:
                    purchase_order.with_company(target_company).sudo().button_confirm()

                log_obj.create({
                    'rule_id': rule.id,
                    'name': _('SO %s -> PO %s') % (so.name, purchase_order.name),
                    'source_company_id': so.company_id.id,
                    'target_company_id': target_company.id,
                    'source_doc_type': 'sale_order',
                    'source_doc_ref': so.name,
                    'target_doc_type': 'purchase_order',
                    'target_doc_ref': purchase_order.name,
                    'amount': purchase_order.amount_total,
                    'currency_id': purchase_order.currency_id.id,
                    'state': 'success',
                    'details': _('Successfully mirrored SO %s to PO %s in company %s.') % (
                        so.name, purchase_order.name, target_company.name
                    )
                })

            except Exception as e:
                log_obj.create({
                    'rule_id': rule.id,
                    'name': _('Failed SO %s Mirroring') % so.name,
                    'source_company_id': so.company_id.id,
                    'target_company_id': target_company.id,
                    'source_doc_type': 'sale_order',
                    'source_doc_ref': so.name,
                    'target_doc_type': 'purchase_order',
                    'target_doc_ref': 'N/A',
                    'amount': so.amount_total,
                    'currency_id': so.currency_id.id,
                    'state': 'error',
                    'details': str(e)
                })

        return res

    def action_view_intercompany_po(self):
        self.ensure_one()
        if not self.intercompany_purchase_order_id:
            raise UserError(_('No mirrored Purchase Order found for this sales order.'))

        return {
            'name': _('Mirrored Purchase Order'),
            'type': 'ir.actions.act_window',
            'res_model': 'purchase.order',
            'res_id': self.intercompany_purchase_order_id.id,
            'view_mode': 'form',
            'target': 'current',
        }
